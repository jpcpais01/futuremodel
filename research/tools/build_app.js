// Builds the app pages.
//   app/index.html   Core v1.0: injects the PLAN object (tools/plan.js) into tools/index.src.html.
//   app/oazy.css     The Oazy Research look, lifted from the Core page so every portfolio shares it.
//   app/oazy-kit.js  The sky and the chart, lifted from the Core page for the other portfolios.
const fs = require('fs');
const path = require('path');
const here = __dirname, app = path.join(here, '..', 'app');
const src = fs.readFileSync(path.join(here, 'index.src.html'), 'utf8');
// tools/plan.js holds the live book, including the tracked wallet address, so it stays on the PC (gitignored).
// Without it the page builds from plan.example.js, which tracks no address.
const planFile = fs.existsSync(path.join(here, 'plan.js')) ? 'plan.js' : 'plan.example.js';
if (planFile !== 'plan.js') console.warn('tools/plan.js not found: building Core from plan.example.js');
const plan = fs.readFileSync(path.join(here, planFile), 'utf8');
if (!src.includes('/*@@PLAN*/')) throw new Error('marker missing');
const out = src.replace('/*@@PLAN*/', () => plan);
fs.writeFileSync(path.join(app, 'index.html'), out);
const m = out.match(/<script>([\s\S]*)<\/script>/);
fs.writeFileSync(path.join(here, '.check.js'), m[1]);

const css = src.match(/<style>([\s\S]*?)<\/style>/)[1];
fs.writeFileSync(path.join(app, 'oazy.css'), '/* Generated by tools/build_app.js from index.src.html. Edit the source. */\n' + css.trim() + '\n');

const a = src.indexOf('/* ── Ambient light'), b = src.indexOf('function spark(');
if (a < 0 || b < a) throw new Error('kit markers missing');
const kit = `/* Generated by tools/build_app.js from index.src.html. Edit the source. */
'use strict';
const $=(s,r=document)=>r.querySelector(s),$$=(s,r=document)=>[...r.querySelectorAll(s)];
const num=v=>v!=null&&Number.isFinite(v);
const esc=s=>String(s??'').replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
const fpx=v=>!num(v)?'—':v>=1000?v.toLocaleString('en-US',{minimumFractionDigits:1,maximumFractionDigits:1}):v>=100?v.toFixed(2):v>=10?v.toFixed(3):v.toFixed(4);
const calm=matchMedia('(prefers-reduced-motion:reduce)').matches;
const R={raf:0};
${src.slice(a, b).trim()}
`;
fs.writeFileSync(path.join(app, 'oazy-kit.js'), kit);
console.log('built', out.length, 'bytes; oazy.css', css.length, '; oazy-kit.js', kit.length);
